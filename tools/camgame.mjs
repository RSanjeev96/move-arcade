import { chromium } from 'playwright';
const browser = await chromium.launch({ executablePath: '/opt/pw-browsers/chromium-1194/chrome-linux/chrome', args: ['--use-gl=angle','--use-angle=swiftshader','--enable-unsafe-swiftshader','--use-fake-ui-for-media-stream','--use-fake-device-for-media-stream',`--use-file-for-fake-video-capture=${process.env.Y4M}`,'--autoplay-policy=no-user-gesture-required'] });
const ctx = await browser.newContext({ viewport: { width: 1280, height: 720 }, permissions: ['camera'] });
const p = await ctx.newPage();
const errs = [];
p.on('pageerror', (e) => errs.push(String(e)));
p.on('console', (m) => m.type() === 'error' && errs.push(m.text()));
const wait = (ms) => new Promise((r) => setTimeout(r, ms));
await p.addInitScript(() => localStorage.setItem('ma.settings', JSON.stringify({ quality: 'low' })));
await p.goto('http://localhost:4173/move-arcade/');
await p.click('#go');
await p.waitForSelector('.calib', { timeout: 40000 });
await wait(4000);
await p.click('#cont');
await wait(1500);
await p.click('[data-go=blade]');
await wait(2000);
await p.click('#play');
await wait(Number(process.env.SECS ?? 12) * 1000);
await p.screenshot({ path: process.argv[2] });
console.log('in game:', !!(await p.$('.blade')), 'errors:', errs.slice(0, 6).join('\n') || 'none');
await browser.close();
